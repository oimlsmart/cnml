#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════
// gen-validators — the precompiled validator generator (the 2026-10-10
// Worker signing audit).
//
// Ajv compiles validators with `new Function`; the Cloudflare Worker
// runtime permits code-from-strings only during isolate startup — and
// the Astro worker loads the API graph lazily, so no request-path
// module ever gets that window. This script compiles EVERY CNML schema
// (the core cross-file graph + every Recommendation) at AUTHOR TIME and
// emits plain functions into src/compiled-validators.ts — the runtime
// imports code, it never compiles. The generated functions carry the
// same error shapes (instancePath/schemaPath/keyword/message) the
// validate module maps, so behavior is byte-equivalent.
//
// Run: node scripts/gen-validators.mjs   (from packages/cnml-xml)
// Node ≥ 23's native type stripping loads the cnml-schemas TS source.
// ═══════════════════════════════════════════════════════════════════
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))
const Ajv = require('../node_modules/ajv/dist/2019.js').default
const standaloneCode = require('../node_modules/ajv/dist/standalone/index.js').default
const draft7MetaSchema = require('../node_modules/ajv/dist/refs/json-schema-draft-07.json')

const { CORE, UNITS, UNITS_LOCAL, MODULES, RECOMMENDATIONS } = await import('../../cnml-schemas/src/index.node.mjs')

const ajv = new Ajv({
  allErrors: true,
  verbose: true,
  strict: false,
  strictSchema: false,
  allowUnionTypes: true,
  code: { source: true, esm: true },
})
ajv.addMetaSchema(draft7MetaSchema)

// The units fill (core_schemas.ts's load-time contract): the structured
// unit definitions declare an empty enum beside enum_file: _units.yaml
// ("populated at load time from the top-level units.enum") — the
// population happens ON A COPY (ajv rejects an empty enum), exactly as
// ensureCoreSchemasRegistered does at runtime.
const unitEnum = UNITS?.units?.enum
let unitsForCompile = UNITS
if (unitEnum && UNITS?.definitions) {
  const copy = JSON.parse(JSON.stringify(UNITS))
  for (const def of Object.values(copy.definitions ?? {})) {
    for (const prop of Object.values(def.properties ?? {})) {
      if (prop.enum_file === '_units.yaml' && Array.isArray(prop.enum) && prop.enum.length === 0) {
        prop.enum = unitEnum
      }
    }
  }
  unitsForCompile = copy
}

// The cross-file $ref targets FIRST (each under its own $id — the refs
// resolve against these), then every recommendation's schema.
// Upstream's $ref convention is schemas-root-relative for every file
// (R → _modules/<name>.yaml and _modules/<name>.yaml → _core.yaml
// alike), while ajv resolves by URI. A fragment therefore registers at
// its nested URI (…/schemas/_modules/<name>.yaml) with its own refs
// re-anchored to absolute — on a deep copy (the shared object is never
// mutated; the units fill below follows the same discipline).
function withAbsoluteRefs(schema, base) {
  const clone = structuredClone(schema)
  const walk = (node) => {
    if (Array.isArray(node)) { node.forEach(walk); return }
    if (!node || typeof node !== 'object') return
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref' && typeof v === 'string' && !v.startsWith('#') && !/^[a-z][a-z0-9+.-]*:/i.test(v)) {
        node[k] = new URL(v, base).href
      } else walk(v)
    }
  }
  walk(clone)
  return clone
}
const schemaBase = new URL('.', CORE.$id).href
// _units.yaml carries no $id either, and the new tier's R schemas
// $ref its shared Unit definition (_units.yaml#/definitions/Unit).
const unitsSchema = (unitsForCompile && typeof unitsForCompile === 'object' && !unitsForCompile.$id)
  ? { ...unitsForCompile, $id: new URL('_units.yaml', schemaBase).href }
  : unitsForCompile
const moduleSchemas = Object.entries(MODULES).map(([name, schema]) =>
  (schema && typeof schema === 'object' && !schema.$id)
    ? withAbsoluteRefs({ ...schema, $id: new URL(`_modules/${name}.yaml`, schemaBase).href }, schemaBase)
    : schema)
for (const schema of [CORE, unitsSchema, UNITS_LOCAL, ...moduleSchemas]) {
  if (schema && typeof schema === 'object' && schema.$id) {
    try { ajv.compile(schema) } catch (e) { console.warn(`${schema.$id}: skipped (${e.message})`) }
  }
}
const exports_ = {}
const skipped = []
for (const rec of RECOMMENDATIONS) {
  if (!rec.schema) continue
  try {
    ajv.compile(rec.schema)
    exports_[rec.id] = rec.schema.$id ?? rec.id
  } catch (e) {
    skipped.push(`${rec.id} (${e.message})`)
  }
}
if (skipped.length) console.warn(`skipped (their schemas trip codegen; runtime fallback compiles them on demand): ${skipped.join('; ')}`)

const code = standaloneCode(ajv, exports_)
const banner = `// GENERATED by scripts/gen-validators.mjs — do not edit by hand.
// The precompiled CNML validators (the Worker-safe posture: no runtime
// code generation anywhere). Regenerate after any schema change:
//   cd packages/cnml-xml && node scripts/gen-validators.mjs
import type { ValidateFunction } from 'ajv'
`
const footer = `
}
`
function convertToEsm(esmCode) {
  // The ESM generator emits everything on one line: `export const NAME =
  // validateN;` statements we rewrite into map entries; the rest stays
  // verbatim (function declarations + schema literals).
  const entries = []
  let kept = esmCode.replace(/export const ([A-Za-z0-9_]+) = ([A-Za-z0-9_]+);/g,
    (_m, name, fn) => { entries.push(`  ${JSON.stringify(name)}: ${fn},`); return '' })
  // The runtime shims the codegen references (equal, etc.) arrive as
  // CJS require calls even in ESM mode — hoist each into a top import.
  const shimImports = new Map()
  kept = kept.replace(/const ([A-Za-z0-9_]+) = require\("([^"]+)"\)\.default;/g,
    (_m, ident, spec) => { shimImports.set(ident, spec); return '' })
  // Node ESM resolves bare subpaths literally — the codegen's runtime
  // requires must name the real .js files (same convention as ajv/dist/2019.js).
  const importLines = [...shimImports.entries()].map(([ident, spec]) =>
    `import ${ident} from '${/\.m?js$/.test(spec) ? spec : `${spec}.js`}'`).join('\n')
  return { kept, entries: entries.join('\n'), importLines }
}

const parts = convertToEsm(code)
const out = banner + parts.importLines + '\nexport const PRECOMPILED: Record<string, ValidateFunction> = {\n' + parts.entries + footer + '\n' + parts.kept
writeFileSync(join(here, '..', 'src', 'compiled-validators.ts'), out)
console.log(`compiled-validators.ts: ${(out.length / 1024).toFixed(0)} KiB, ${Object.keys(exports_).length} recommendation validators + core ref graph`)
